import assert from 'node:assert/strict';
import { test } from 'node:test';
import { mkdtempSync, readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import {
  addStackItems,
  parseStandardOptions,
  scaffoldStandardProject,
  readProjectSection,
  writeProjectSection,
} from '../dist/index.js';
import { sourceFiles, recordScaffoldFiles } from '../dist/registry/receipt.js';
async function fixture(run) {
  const temporary = mkdtempSync(path.join(tmpdir(), 'anhedral-payment-add-'));
  const root = path.join(temporary, 'app');
  try {
    await scaffoldStandardProject(
      parseStandardOptions([root, '--skip-install', '--no-git', '--json']),
      () => assert.fail('offline init'),
      { quiet: true },
    );
    writeFileSync(path.join(root, 'pnpm-lock.yaml'), 'lockfileVersion: "9.0"\n');
    recordScaffoldFiles(root);
    return await run(root);
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}
const runner = (command, args, cwd) => {
  assert.equal(command, 'pnpm');
  assert.ok(args.includes('--lockfile-only'), args.join(' '));
  writeFileSync(path.join(cwd, 'pnpm-lock.yaml'), 'lockfileVersion: "9.0"\n');
};

test('payment preview is read-only and excludes secrets; applying is idempotent', () =>
  fixture(async (root) => {
    writeFileSync(path.join(root, 'apps/api/.dev.vars'), 'PRIVATE_TEST_VALUE=do-not-preview');
    const before = sourceFiles(root);
    const request = {
      items: ['stripe'],
      dryRun: true,
      preview: { mode: 'view', path: 'packages/billing/src/index.ts' },
    };
    const preview = await addStackItems(root, request, runner);
    assert.ok(preview.previews.length);
    assert.ok(preview.previews.every((p) => !p.path.includes('.dev.vars')));
    assert.doesNotMatch(JSON.stringify(preview), /do-not-preview/);
    assert.deepEqual(sourceFiles(root), before);
    assert.equal(existsSync(path.join(root, 'packages/billing')), false);
    await addStackItems(root, { items: ['stripe'], skipInstall: true }, runner);
    assert.ok(readProjectSection(root, 'setup').products.includes('stripe'));
    assert.equal(
      readFileSync(path.join(root, 'apps/api/.dev.vars'), 'utf8'),
      'PRIVATE_TEST_VALUE=do-not-preview',
    );
    const applied = sourceFiles(root);
    await addStackItems(root, { items: ['stripe'], skipInstall: true }, runner);
    assert.deepEqual(sourceFiles(root), applied);
  }));

test('RevenueCat can be added independently and then combined with Stripe', () =>
  fixture(async (root) => {
    await addStackItems(root, { items: ['revenuecat'], skipInstall: true }, runner);
    assert.ok(readProjectSection(root, 'setup').products.includes('revenuecat'));
    assert.ok(!readProjectSection(root, 'setup').products.includes('stripe'));
    await addStackItems(root, { items: ['stripe'], skipInstall: true }, runner);
    const products = readProjectSection(root, 'setup').products;
    assert.ok(products.includes('stripe') && products.includes('revenuecat'));
  }));

test('add rejects retired/core selectors, private previews and stale generator provenance', () =>
  fixture(async (root) => {
    for (const id of ['resend', 'neon', 'next', 'workers-ai', 'd1', 'r2'])
      await assert.rejects(
        addStackItems(root, { items: [id], dryRun: true }, runner),
        /Unknown stack product/,
      );
    await assert.rejects(
      addStackItems(
        root,
        { items: ['stripe'], dryRun: true, preview: { mode: 'view', path: '.dev.vars' } },
        runner,
      ),
    );
    const setup = readProjectSection(root, 'setup');
    writeProjectSection(root, 'setup', { ...setup, cliVersion: '0.0.0' });
    await assert.rejects(
      addStackItems(root, { items: ['stripe'], dryRun: true }, runner),
      /generated by|CLI version/,
    );
  }));

test('authored source conflicts are preserved when adding payments', () =>
  fixture(async (root) => {
    const file = path.join(root, 'apps/api/src/index.ts');
    const edited = readFileSync(file, 'utf8') + '\n// customer endpoint\n';
    writeFileSync(file, edited);
    await assert.rejects(
      addStackItems(root, { items: ['stripe'], skipInstall: true }, runner),
      /edited|conflict|changed|modified/i,
    );
    assert.equal(readFileSync(file, 'utf8'), edited);
    assert.equal(existsSync(path.join(root, 'packages/billing')), false);
  }));

test('failed dependency resolution rolls back the addition', () =>
  fixture(async (root) => {
    const before = sourceFiles(root);
    await assert.rejects(
      addStackItems(root, { items: ['stripe'], skipInstall: true }, () => {
        throw Error('isolated resolver failure');
      }),
      /resolver failure/,
    );
    assert.deepEqual(sourceFiles(root), before);
    assert.ok(!readProjectSection(root, 'setup').products.includes('stripe'));
  }));
