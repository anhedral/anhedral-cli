import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync, gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { format, resolveConfig } from 'prettier';
import { loadOfficialRegistry } from './shadcn-registry.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const hash = (value) => createHash('sha256').update(value).digest('hex');
const asset = path.join(root, 'assets/ui/native-icons.json.gz');
const sourceFile = path.join(root, 'assets/ui/native/registry-icons.tsx');
export function loadNativeIcons() {
  return JSON.parse(gunzipSync(readFileSync(asset)));
}
export function validateNativeIcons(inventory, catalog) {
  if (catalog.schemaVersion !== 1 || catalog.upstream.commit !== inventory.source.commit)
    throw Error('Stale native icon source pin.');
  const expected = Object.entries(inventory.sources)
    .filter(([, input]) =>
      input.imports.some((name) => name.endsWith('/components/icon-placeholder')),
    )
    .map(([origin]) => origin)
    .sort();
  if (JSON.stringify(expected) !== JSON.stringify(Object.keys(catalog.inputs).sort()))
    throw Error('Native icon caller inventory changed.');
  for (const [origin, sha256] of Object.entries(catalog.inputs))
    if (inventory.sources[origin]?.sha256 !== sha256)
      throw Error('Stale native icon caller: ' + origin);
  if (hash(readFileSync(sourceFile)) !== catalog.nativeSha256)
    throw Error('Changed native icon output.');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const inventory = loadOfficialRegistry(),
    index = process.argv.indexOf('--source');
  if (index < 0) {
    validateNativeIcons(inventory, loadNativeIcons());
    console.log('Native registry icon evidence passed.');
  } else {
    if (!process.argv[index + 1])
      throw Error('Pass --source /absolute/path/to/the/pinned/shadcn-ui');
    const names = new Set(),
      inputs = {};
    for (const [origin, input] of Object.entries(inventory.sources).filter(
      ([name]) => !name.includes('#'),
    )) {
      const text = readFileSync(path.join(process.argv[index + 1], origin), 'utf8');
      if (!text.includes('IconPlaceholder')) continue;
      if (hash(text) !== input.sha256) throw Error('Native icon source drift: ' + origin);
      const file = ts.createSourceFile(
        origin,
        text,
        ts.ScriptTarget.Latest,
        true,
        ts.ScriptKind.TSX,
      );
      function visit(node) {
        if (
          (ts.isJsxOpeningElement(node) || ts.isJsxSelfClosingElement(node)) &&
          node.tagName.getText(file) === 'IconPlaceholder'
        ) {
          const attr = node.attributes.properties.find(
            (attr) => ts.isJsxAttribute(attr) && attr.name.getText(file) === 'lucide',
          );
          if (!attr?.initializer || !ts.isStringLiteral(attr.initializer))
            throw Error('Unreviewed dynamic registry icon: ' + origin);
          names.add(attr.initializer.text);
          inputs[origin] = input.sha256;
        }
        ts.forEachChild(node, visit);
      }
      visit(file);
    }
    const icons = [...names].sort();
    for (const icon of icons)
      if (!/^[A-Z][a-zA-Z0-9]+$/.test(icon)) throw Error('Unsafe registry icon name.');
    const source =
      '// Official shadcn registry Lucide selections; generated by scripts/native-icons.mjs.\n' +
      'import { ' +
      icons.join(', ') +
      ' } from "lucide-react-native";\n' +
      'import { withRegistryStyles } from "./registry-styles";\n' +
      'export const nativeRegistryIcons = {\n' +
      icons.map((icon) => `  ${icon}: withRegistryStyles(${icon}, 'icon'),`).join('\n') +
      '\n};\n';
    const native = await format(source, {
      ...(await resolveConfig(sourceFile)),
      filepath: sourceFile,
    });
    writeFileSync(sourceFile, native);
    writeFileSync(
      asset,
      gzipSync(
        JSON.stringify({
          schemaVersion: 1,
          upstream: inventory.source,
          inputs,
          icons,
          nativeSha256: hash(native),
        }),
        { level: 9 },
      ),
    );
    console.log('Recorded', icons.length, 'official Lucide native selections.');
  }
}
